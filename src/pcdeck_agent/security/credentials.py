"""Paired-device registry. Stores only SHA-256 hashes of device tokens.

At rest: Windows encrypts the file with DPAPI (current user). Linux / macOS have no DPAPI: the same
JSON is written to the per-user config dir as a file only its owner can read (0600).
Tokens are 256-bit random values generated by the agent at pairing time and returned once to the
device; the agent never stores or logs them in clear text (a leaked hash does not let anyone
authenticate). Each device has its own token, so one device can be revoked without affecting the others.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import logging
import os
import secrets
import stat
import sys
import threading
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from . import dpapi

log = logging.getLogger(__name__)
SCHEMA = 1


@dataclass
class PairedDevice:
    client_id: str
    name: str
    token_sha256: str
    paired_at: float
    last_seen: float = 0.0


def write_private(path: Path, data: bytes) -> None:
    """POSIX: create/overwrite ``path`` readable and writable by its owner only (0600); a missing
    directory is created 0700."""
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        os.fchmod(fd, 0o600)  # O_CREAT does not change the mode of an existing file
        os.write(fd, data)
    finally:
        os.close(fd)


def _hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


class CredentialStore:
    def __init__(self, path: Path, *, encrypt: bool = True) -> None:
        self.path = path
        self.encrypt = encrypt and sys.platform == "win32"  # DPAPI; elsewhere an owner-only file
        self._lock = threading.Lock()
        self._devices: dict[str, PairedDevice] = {}
        self._load()

    # ---- persistence ----------------------------------------------------------------------------
    def _load(self) -> None:
        if not self.path.exists():
            return
        if os.name != "nt" and stat.S_IMODE(self.path.stat().st_mode) & 0o077:
            log.warning("%s was readable by other users; restricting it to the owner", self.path)
            os.chmod(self.path, 0o600)
        try:
            raw = self.path.read_bytes()
            data = json.loads(dpapi.unprotect(raw) if self.encrypt else raw)
            if data.get("schema") != SCHEMA:
                raise ValueError("schema mismatch")
            self._devices = {d["client_id"]: PairedDevice(**d) for d in data.get("devices", [])}
        except Exception as e:  # corrupted / other user / other machine: start empty, keep the file aside
            backup = self.path.with_suffix(".unreadable")
            log.error("paired-device store unreadable (%s); moved to %s, devices must pair again", e.__class__.__name__, backup)
            try:
                self.path.replace(backup)
            except OSError:
                pass
            self._devices = {}

    def _save(self) -> None:
        payload = json.dumps({"schema": SCHEMA, "devices": [asdict(d) for d in self._devices.values()]}).encode("utf-8")
        blob = dpapi.protect(payload) if self.encrypt else payload
        tmp = self.path.with_suffix(".tmp")
        if os.name == "nt":
            self.path.parent.mkdir(parents=True, exist_ok=True)
            tmp.write_bytes(blob)
        else:
            write_private(tmp, blob)
        tmp.replace(self.path)

    # ---- API --------------------------------------------------------------------------------------
    def add(self, client_id: str, name: str) -> str:
        """Create (or replace) the credential for a device. Returns the clear token ONCE."""
        token = secrets.token_urlsafe(32)
        with self._lock:
            self._devices[client_id] = PairedDevice(client_id=client_id, name=name[:40], token_sha256=_hash(token), paired_at=time.time())
            self._save()
        log.info("device paired: %s (%s)", client_id, name[:40])
        return token

    def verify(self, client_id: str, token: str) -> bool:
        with self._lock:
            dev = self._devices.get(client_id)
            expected = dev.token_sha256 if dev else _hash("\x00invalid")  # constant work for unknown ids
            ok = hmac.compare_digest(expected, _hash(token)) and dev is not None
            if ok and dev is not None:
                dev.last_seen = time.time()
            return ok

    def revoke(self, client_id: str) -> bool:
        with self._lock:
            removed = self._devices.pop(client_id, None) is not None
            if removed:
                self._save()
        if removed:
            log.info("device revoked: %s", client_id)
        return removed

    def devices(self) -> list[PairedDevice]:
        with self._lock:
            return sorted(self._devices.values(), key=lambda d: d.paired_at)

    def touch_save(self) -> None:
        """Persist last_seen timestamps (called rarely)."""
        with self._lock:
            self._save()
